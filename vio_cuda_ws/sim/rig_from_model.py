"""Generate config/rig_sim.yaml from the drone model files in the PX4-Autopilot repo.

  imu_link   = PX4's IMU: sensor `imu_sensor` on link `base_link` of x500_base
  camera     = D435 mount in x500_d435 (the include pose of the realsense model)
  IMU noise  = imu_sensor's per-sample Gaussian stddev -> continuous noise density (sigma / sqrt(rate))

It also checks that our sim/models/x500_d435_vio mounts the camera exactly as x500_d435 does,
so the rig matches the drone that is actually spawned. Run after changing either model:
    python3 sim/rig_from_model.py
SDF rules used: an included model without its own <pose> in the <include> keeps the model's
<pose>; link and sensor poses are relative to their parent. Poses are x y z roll pitch yaw.
"""
import math
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

import numpy as np

PX4_MODELS = Path.home() / 'PX4-Autopilot/Tools/simulation/gz/models'
HERE = Path(__file__).resolve().parent
OUT = HERE.parent / 'src/vio_bringup/config/rig_sim.yaml'
# cuVSLAM needs non-zero bias random walks; the gz IMU has no bias model, so use small floors
RANDOM_WALK_FLOOR = {'gyro': 2.0e-5, 'accel': 3.0e-3}


def pose_matrix(text):
    v = [float(x) for x in (text or '0 0 0 0 0 0').split()]
    x, y, z, r, p, w = v + [0.0] * (6 - len(v))
    cr, sr, cp, sp, cy, sy = math.cos(r), math.sin(r), math.cos(p), math.sin(p), math.cos(w), math.sin(w)
    m = np.eye(4)
    m[:3, :3] = [[cy * cp, cy * sp * sr - sy * cr, cy * sp * cr + sy * sr],
                 [sy * cp, sy * sp * sr + cy * cr, sy * sp * cr - cy * sr],
                 [-sp, cp * sr, cp * cr]]
    m[:3, 3] = [x, y, z]
    return m


def child_pose(elem):
    p = elem.find('pose')
    return pose_matrix(p.text if p is not None else None)


def model(path):
    return ET.parse(path).getroot().find('model')


def include_pose(parent_model, uri_suffix):
    for inc in parent_model.findall('include'):
        if inc.findtext('uri', '').endswith(uri_suffix):
            return inc.find('pose')
    sys.exit(f'no <include> of {uri_suffix} in {parent_model.get("name")}')


def rot_to_quat(r):
    w = math.sqrt(max(0.0, 1 + r[0, 0] + r[1, 1] + r[2, 2])) / 2
    x = math.copysign(math.sqrt(max(0.0, 1 + r[0, 0] - r[1, 1] - r[2, 2])) / 2, r[2, 1] - r[1, 2])
    y = math.copysign(math.sqrt(max(0.0, 1 - r[0, 0] + r[1, 1] - r[2, 2])) / 2, r[0, 2] - r[2, 0])
    z = math.copysign(math.sqrt(max(0.0, 1 - r[0, 0] - r[1, 1] + r[2, 2])) / 2, r[1, 0] - r[0, 1])
    q = np.array([x, y, z, w])
    return q / np.linalg.norm(q)


def main():
    base = model(PX4_MODELS / 'x500_base/model.sdf')
    link = next(l for l in base.findall('link') if l.get('name') == 'base_link')
    imu = next(s for s in link.findall('sensor') if s.get('name') == 'imu_sensor')
    # x500 includes x500_base and x500_d435 includes x500, both without an include pose,
    # so x500_base keeps its own model pose
    t_model_imu = child_pose(base) @ child_pose(link) @ child_pose(imu)

    d435 = model(PX4_MODELS / 'x500_d435/model.sdf')
    mount = include_pose(d435, 'realsense_d435')
    t_model_cam = pose_matrix(mount.text)

    ours = model(HERE / 'models/x500_d435_vio/model.sdf')
    our_mount = include_pose(ours, 'realsense_d435_vio')
    if not np.allclose(pose_matrix(our_mount.text), t_model_cam):
        sys.exit(f'sim/models/x500_d435_vio mounts the camera at "{our_mount.text}", but PX4\'s '
                 f'x500_d435 uses "{mount.text}" - make them match first')

    t_imu_cam = np.linalg.inv(t_model_imu) @ t_model_cam
    trans = [round(float(v), 6) for v in t_imu_cam[:3, 3]]
    quat = [round(float(v), 6) for v in rot_to_quat(t_imu_cam[:3, :3])]

    rate = float(imu.findtext('update_rate'))
    def sigma(kind):  # largest per-axis stddev, per sample
        return max(float(imu.find(f'imu/{kind}/{a}/noise/stddev').text) for a in 'xyz')
    gyro_nd = sigma('angular_velocity') / math.sqrt(rate)
    accel_nd = sigma('linear_acceleration') / math.sqrt(rate)

    OUT.write_text(f"""# GENERATED by sim/rig_from_model.py from the PX4-Autopilot drone models - don't edit by hand.
#   IMU:    {PX4_MODELS}/x500_base/model.sdf  (imu_sensor on base_link, {rate:.0f} Hz)
#   camera: {PX4_MODELS}/x500_d435/model.sdf  (realsense mount "{mount.text.strip()}")
# imu_link = PX4's IMU (x500 base_link); camera_link = the D435.
source: sim (PX4 x500_base + x500_d435 models)

imu_to_camera:
  translation: {trans}
  rotation_xyzw: {quat}

# IMU stamps in sim come from PX4's own clock (= Gazebo sim time), but the samples lag the true motion
# by 4 ms (one 250 Hz sample; PX4 HIGHRES_IMU) - measured by tests/vio_frames_check.py, 2026-10-19
time_offset: -0.004

# From imu_sensor's per-sample Gaussian noise: density = stddev / sqrt({rate:.0f} Hz).
# The gz IMU has no bias model, so the random walks are small fixed floors.
imu_noise:
  gyro_noise_density: {gyro_nd:.3e}
  gyro_random_walk: {RANDOM_WALK_FLOOR['gyro']:.1e}
  accel_noise_density: {accel_nd:.3e}
  accel_random_walk: {RANDOM_WALK_FLOOR['accel']:.1e}
  rate_hz: 200.0
""")
    print(f'wrote {OUT}\n  imu -> camera {trans}, q {quat}\n'
          f'  gyro noise density {gyro_nd:.3e} rad/s/sqrt(Hz), accel {accel_nd:.3e} m/s^2/sqrt(Hz)')


if __name__ == '__main__':
    main()
